#!/usr/bin/env node
'use strict';
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const index=read('apps-script/core-engine/owner-portal-next/Portal_Index.html');
const daily=read('apps-script/core-engine/owner-portal-next/Portal_DailyFirst_Client.html');
const dailyStyles=read('apps-script/core-engine/owner-portal-next/Portal_DailyFirst_Styles.html');
const chromebookStyles=read('apps-script/core-engine/owner-portal-next/Portal_Chromebook_Styles.html');
const mobile=read('apps-script/core-engine/owner-portal-next/Portal_Mobile_Field_Client.html');
const failures=[];
const check=(name,condition)=>{if(!condition)failures.push(name);};
const finalStyle=(index.match(/<style id="h38-final-readable-phone">([\s\S]*?)<\/style>/)||[])[1]||'';
check('final Today bridge marker',index.includes("window.H38ReadableTodayRoute='direct-extra-large-v2'"));
check('Today route directly invokes readable renderer',index.includes("typeof h38DailyRender==='function')return h38DailyRender()"));
check('phone upgrade persists Extra Large',index.includes("localStorage.setItem('h38MobileTextSize','extra')"));
check('readable renderer exists',daily.includes('function h38DailyRender()'));
check('readable renderer limits attention',daily.includes('rows:unique.slice(0,2)'));
check('mobile shell exposes Find',mobile.includes('<span>Find</span>'));
check('phone sizing is class driven',index.includes("window.H38ReadableShell='class-driven-oversized-controls-v5'"));
check('phone sizing is not trapped in viewport media query',!finalStyle.includes('@media(max-width:720px)'));
check('phone base text is materially larger',finalStyle.includes('font-size:24px!important'));
check('top controls are materially larger',finalStyle.includes('grid-template-columns:78px minmax(0,1fr) 78px 78px!important'));
check('phone status is materially larger',finalStyle.includes('.h38-mobile-top-title small')&&finalStyle.includes('font-size:24px!important'));
check('bottom navigation is materially taller',finalStyle.includes('height:calc(132px + env(safe-area-inset-bottom))!important'));
check('bottom navigation labels are materially larger',finalStyle.includes('.mobile-bottom-nav button span')&&finalStyle.includes('font-size:24px!important'));
check('attention supporting text is materially larger',finalStyle.includes('.h38-daily-item small{font-size:23px!important'));
check('secondary setup control is materially larger',finalStyle.includes('.h38-daily-more summary{font-size:27px!important'));
check('readable Chromebook shell marker',chromebookStyles.includes('Readable Chromebook shell v2'));
check('Chromebook sidebar is wider',chromebookStyles.includes('--h38-sidebar:236px'));
check('Chromebook navigation items are readable',chromebookStyles.includes('.nav-group-items button{min-height:48px!important')&&chromebookStyles.includes('font-size:16px!important'));
check('Chromebook toolbar is readable',chromebookStyles.includes('#ownerTopbar{min-height:68px!important')&&chromebookStyles.includes('#ownerTopbar .btn{min-height:50px!important'));
check('Chromebook workspace has useful padding',chromebookStyles.includes('#view{padding:18px 24px 96px!important'));
check('Chromebook Today layout marker',dailyStyles.includes('Chromebook Today layout v2'));
check('Chromebook Today uses balanced columns',dailyStyles.includes('grid-template-columns:minmax(0,1.15fr) minmax(360px,.85fr)'));
check('Chromebook attention occupies second column',dailyStyles.includes('.h38-daily-attention{grid-column:2'));
check('Chromebook quick actions use two columns',dailyStyles.includes('.h38-daily-quick{grid-template-columns:repeat(2,minmax(0,1fr))'));
check('phone Today selectors remain present',dailyStyles.includes('body.h38-phone-shell .h38-daily-next{grid-template-columns:1fr'));
const result={status:failures.length?'FAIL':'PASS',failed:failures.length,failures};
console.log(JSON.stringify(result,null,2));
process.exit(failures.length?1:0);
