const fs=require('fs');
const path=require('path');
const assert=require('assert');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const recurring=read('commercial-app/recurring-service-runtime.js');
const labor=read('commercial-app/multi-rate-labor-runtime.js');
const plow=read('commercial-app/plow-trigger-runtime.js');
const css=read('commercial-app/service-operations-final.css');
const loader=read('commercial-app/live-customer-navigation-guard-20260910.js');
const pack=JSON.parse(read('business-packs/northern-lakes/supabase-business-pack.json'));
const assistant=read('supabase/functions/h38-assistant-ai/index.ts');
const quote=read('supabase/functions/h38-quote-options/index.ts');
for(const marker of ["'Site Visit Required':false","'Quote Required':false",'Finish','Delete','Soft delete — audit retained']) assert(recurring.includes(marker),`Recurring service contract missing: ${marker}`);
for(const marker of ['Multiple labor rates','People','Hours each','Rate / hour',"'Billing Method':'Multi-rate labor'","'Approval Status':'Owner Approval Required'","'Send Allowed':'No'"]) assert(labor.includes(marker),`Multi-rate labor contract missing: ${marker}`);
for(const marker of ['Automatic snow plowing','Trigger all automatic snow plow jobs',"'Automatic Plowing'",'alreadyToday',"'Subscribed Service':true"]) assert(plow.includes(marker),`Plow trigger contract missing: ${marker}`);
assert(css.includes('.h38-life-work.h38-recurring-simple'),'Recurring service simplified lifecycle style missing.');
for(const file of ['recurring-service-runtime.js','multi-rate-labor-runtime.js','plow-trigger-runtime.js']) assert(loader.includes(file),`Shared loader missing ${file}`);
assert.equal(pack.ai?.provider,'openai');
assert.equal(pack.ai?.credentialSource,'shared-server-openai-api-key');
assert.equal(pack.ai?.billingOwner,'Highway 38 Solutions');
assert.equal(pack.ai?.tenantMaySupplySeparateKey,false);
assert.equal(pack.ai?.browserKeyExposure,false);
for(const source of [assistant,quote]) assert(source.includes('Deno.env.get("OPENAI_API_KEY")'),'Shared Supabase AI must use server OPENAI_API_KEY.');
assert.equal(pack.safeguards?.automaticCustomerSending,false);
assert.equal(pack.safeguards?.automaticFinancialActions,false);
assert.equal(pack.safeguards?.ownerApprovalRequired,true);
console.log('Service operations final verification passed.');
